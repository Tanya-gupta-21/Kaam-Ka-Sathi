-- Shared quota for AI drafting and relevance review.
-- Safe to apply after the initial schema whether or not it already contains this feature.
create table if not exists public.ai_assistant_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists ai_assistant_usage_user_created_idx
  on public.ai_assistant_usage (user_id, created_at desc);

alter table public.ai_assistant_usage enable row level security;

create or replace function public.consume_ai_assistant_request()
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_count integer;
begin
  if v_user_id is null then
    raise exception 'Sign in to use the AI assistant' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(hashtext(v_user_id::text));
  delete from public.ai_assistant_usage
    where user_id = v_user_id and created_at < now() - interval '1 hour';
  select count(*) into v_count from public.ai_assistant_usage
    where user_id = v_user_id and created_at >= now() - interval '1 hour';
  if v_count >= 20 then
    return false;
  end if;
  insert into public.ai_assistant_usage (user_id) values (v_user_id);
  return true;
end;
$$;

grant execute on function public.consume_ai_assistant_request() to authenticated;
revoke all on function public.consume_ai_assistant_request() from public, anon;
