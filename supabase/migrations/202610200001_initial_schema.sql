create or replace function public.admin_set_user_role(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select auth.uid()) is null or not public.is_admin() then
    raise exception 'Only admins can change roles' using errcode = '42501';
  end if;
  if p_role not in ('user', 'admin') then
    raise exception 'Invalid role';
  end if;
  update public.profiles set role = p_role where id = p_user_id;
end;
$$;

create or replace function public.start_handover(p_item_id bigint, p_receiver_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_giver_id uuid := (select auth.uid());
  v_handover_id uuid;
begin
  if v_giver_id is null or p_receiver_id = v_giver_id then
    raise exception 'Invalid handover participants';
  end if;
  if not exists (select 1 from public.items where id = p_item_id and owner_id = v_giver_id) then
    raise exception 'You do not own this item' using errcode = '42501';
  end if;
  if not (
    exists (select 1 from public.interests where item_id = p_item_id and interested_user_id = p_receiver_id)
    or exists (select 1 from public.conversations where item_id = p_item_id and interested_user_id = p_receiver_id)
  ) then
    raise exception 'The receiver has not expressed interest';
  end if;
  insert into public.item_handovers (item_id, giver_id, receiver_id)
  values (p_item_id, v_giver_id, p_receiver_id)
  returning id into v_handover_id;
  return v_handover_id;
end;
$$;

create or replace function public.respond_handover(p_handover_id uuid, p_accept boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_handover public.item_handovers%rowtype;
begin
  if (select auth.uid()) is null then
    raise exception 'Sign in to respond to a handover' using errcode = '42501';
  end if;
  select * into v_handover from public.item_handovers
  where id = p_handover_id for update;
  if not found or v_handover.receiver_id <> (select auth.uid()) then
    raise exception 'Handover not found or access denied' using errcode = '42501';
  end if;
  if v_handover.status <> 'pending' then
    raise exception 'This handover has already been answered';
  end if;
  update public.item_handovers
  set status = case when p_accept then 'confirmed' else 'declined' end,
      confirmed_at = case when p_accept then now() else null end
  where id = p_handover_id;
  if p_accept then
    update public.profiles set points = points + 10 where id = v_handover.giver_id;
    update public.profiles set points = points + 2 where id = v_handover.receiver_id;
  end if;
end;
$$;

create or replace function public.consume_ai_photo_check()
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_count integer;
begin
  if v_user_id is null then
    raise exception 'Sign in to use photo checking' using errcode = '42501';
  end if;

  -- Serialize requests by account so simultaneous requests cannot bypass the cap.
  perform pg_advisory_xact_lock(hashtext(v_user_id::text));
  delete from public.ai_photo_usage
    where user_id = v_user_id and created_at < now() - interval '1 hour';
  select count(*) into v_count from public.ai_photo_usage
    where user_id = v_user_id and created_at >= now() - interval '1 hour';
  if v_count >= 20 then
    return false;
  end if;
  insert into public.ai_photo_usage (user_id) values (v_user_id);
  return true;
end;
$$;

create or replace function public.consume_ai_assistant_request()
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_count integer;
begin
  if v_user_id is null then
    raise exception 'Sign in to use the AI assistant' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(hashtext(v_user_id::text));
  delete from public.ai_assistant_usage
    where user_id = v_user_id and created_at < now() - interval '1 hour';
  select count(*) into v_count from public.ai_assistant_usage
    where user_id = v_user_id and created_at >= now() - interval '1 hour';
  if v_count >= 20 then
    return false;
  end if;
  insert into public.ai_assistant_usage (user_id) values (v_user_id);
  return true;
end;
$$;

create or replace function public.notify_new_interest()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_owner uuid;
  v_title text;
begin
  select owner_id, title into v_owner, v_title from public.items where id = new.item_id;
  if v_owner is not null and v_owner <> new.interested_user_id then
    insert into public.notifications (user_id, type, title, message, payload)
    values (v_owner, 'new_interest', 'Someone is interested in your item', v_title,
      jsonb_build_object('item_id', new.item_id, 'url', '/dashboard/interests'));
  end if;
  return new;
end;
$$;

