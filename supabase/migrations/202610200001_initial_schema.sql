insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('item-images', 'item-images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp']),
  ('avatars', 'avatars', true, 2097152, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

create policy "public reads listing and avatar images" on storage.objects
  for select to public using (bucket_id in ('item-images', 'avatars'));
create policy "users upload images to their own folder" on storage.objects
  for insert to authenticated with check (
    bucket_id in ('item-images', 'avatars') and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy "users update their own images" on storage.objects
  for update to authenticated using (
    bucket_id in ('item-images', 'avatars') and (storage.foldername(name))[1] = (select auth.uid())::text
  ) with check (
    bucket_id in ('item-images', 'avatars') and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy "users delete their own images" on storage.objects
  for delete to authenticated using (
    bucket_id in ('item-images', 'avatars') and (storage.foldername(name))[1] = (select auth.uid())::text
  );

-- Enable the realtime feeds used by chat and the notification bell.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages') then
      alter publication supabase_realtime add table public.messages;
    end if;
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notifications') then
      alter publication supabase_realtime add table public.notifications;
    end if;
  end if;
end;
$$;
