create or replace function public.notify_new_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_recipient uuid;
begin
  select case when owner_id = new.sender_id then interested_user_id else owner_id end
  into v_recipient from public.conversations where id = new.conversation_id;
  if v_recipient is not null then
    insert into public.notifications (user_id, type, title, message, payload)
    values (v_recipient, 'new_message', 'New message', left(new.message, 180),
      jsonb_build_object('conversation_id', new.conversation_id, 'url', '/chat/' || new.conversation_id));
  end if;
  return new;
end;
$$;

