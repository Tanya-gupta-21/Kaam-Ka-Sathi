create or replace function public.notify_handover_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item_title text;
begin
  select title into v_item_title from public.items where id = new.item_id;
  if tg_op = 'INSERT' then
    insert into public.notifications (user_id, type, title, message, payload)
    values (new.receiver_id, 'handover_pending', 'Item handover requested', coalesce(v_item_title, 'An item'),
      jsonb_build_object('item_id', new.item_id, 'url', '/handovers'));
  elsif new.status <> old.status then
    insert into public.notifications (user_id, type, title, message, payload)
    values (new.giver_id, 'handover_response',
      case when new.status = 'confirmed' then 'Handover confirmed' else 'Handover declined' end,
      coalesce(v_item_title, 'An item'), jsonb_build_object('item_id', new.item_id, 'url', '/handovers'));
  end if;
  return new;
end;
$$;

create trigger item_handover_notification
  after insert or update of status on public.item_handovers
  for each row execute procedure public.notify_handover_change();

