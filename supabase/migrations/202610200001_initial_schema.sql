create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  email text,
  phone text,
  city text,
  locality text,
  avatar_url text,
  bio text,
  role text not null default 'user' check (role in ('user', 'admin')),
  points integer not null default 0 check (points >= 0),
  last_seen timestamptz,
  created_at timestamptz not null default now()
);

create table public.items (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles (id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 120),
  description text not null default '',
  category text not null default 'Other',
  condition text not null default 'Used',
  city text,
  locality text,
  image_url text,
  listing_mode text not null default 'give'
    check (listing_mode in ('give', 'sell', 'rent', 'lend')),
  price numeric(12, 2) check (price is null or price >= 0),
  price_period text,
  duration_days integer check (duration_days is null or duration_days between 1 and 3650),
  security_deposit numeric(12, 2) check (security_deposit is null or security_deposit >= 0),
  latitude double precision,
  longitude double precision,
  location_address text,
  created_at timestamptz not null default now()
);

create table public.needs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 120),
  description text,
  category text not null default 'Other',
  city text,
  locality text,
  created_at timestamptz not null default now()
);

create table public.interests (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.items (id) on delete cascade,
  interested_user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (item_id, interested_user_id)
);

create table public.need_interests (
  id bigint generated by default as identity primary key,
  need_id bigint not null references public.needs (id) on delete cascade,
  interested_user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (need_id, interested_user_id)
);

create table public.services (
  id uuid primary key default gen_random_uuid(),
  provider_id uuid not null references public.profiles (id) on delete cascade,
  category text not null check (length(trim(category)) between 1 and 80),
  title text not null check (length(trim(title)) between 1 and 120),
  description text not null default '' check (length(description) <= 2000),
  city text not null,
  locality text,
  price numeric(12, 2) check (price is null or price >= 0),
  price_unit text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  interested_user_id uuid not null references public.profiles (id) on delete cascade,
  item_id bigint references public.items (id) on delete cascade,
  need_id bigint references public.needs (id) on delete cascade,
  service_id uuid references public.services (id) on delete cascade,
  created_at timestamptz not null default now(),
  check (owner_id <> interested_user_id),
  check (
    (service_id is not null and item_id is null and need_id is null)
    or (service_id is null and (item_id is not null or need_id is not null))
  )
);

create unique index conversations_item_interest_unique
